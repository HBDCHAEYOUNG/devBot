const getDifficultyDescription = (difficulty: Difficulty): string => {
  const descriptions = {
    beginner:
      "입문자 대상. 기본 개념과 용어를 자세히 설명하고 쉬운 예시를 사용합니다.",
    intermediate:
      "중급자 대상. 개념 설명은 간략히 하고 코드 예제와 실전 사용 방법을 중심으로 설명합니다.",
    advanced:
      "고급자 대상. 기본 개념 설명은 최소화하고 아키텍처 설계, 성능 최적화, 트러블슈팅 등 심화 내용을 중심으로 설명합니다.",
  };
  return descriptions[difficulty];
};

const getLengthDescription = (length: Length): string => {
  const descriptions = {
    short: "간결한 글 (약 3~4개 섹션)",
    medium: "표준 길이 글 (약 4~6개 섹션)",
    long: "심화 설명 글 (약 6~8개 섹션)",
  };
  return descriptions[length];
};

